def convert_text(text: str, to_traditional: bool = True) -> str:
    """Convert text between Simplified and Traditional Chinese.
    
    Args:
        text: Input text to convert
        to_traditional: True for Simplified→Traditional, False for Traditional→Simplified
    
    Returns:
        Converted text with Chinese characters transformed.
        Non-Chinese characters (English, numbers, punctuation) are preserved.
    
    Example:
        >>> convert_text("我们决定使用PostgreSQL", to_traditional=True)
        '我們決定使用PostgreSQL'
        >>> convert_text("我們決定使用PostgreSQL", to_traditional=False)
        '我们决定使用PostgreSQL'
    """
    mapping = SIMPLIFIED_TO_TRADITIONAL if to_traditional else TRADITIONAL_TO_SIMPLIFIED
    result = []
    
    for char in text:
        if char in mapping:
            result.append(mapping[char])
        else:
            result.append(char)
    
    return "".join(result)


